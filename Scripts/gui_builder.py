def on_submit(state, reason):
    """Called on every submit.  state: dict of field values.
    reason: 'button', 'timer', 'change', 'stdin' or 'event:<button key>'."""
    out = json.dumps(state) if SPEC["format"] == "json" else repr(state)
    print(out, flush=True)
    if SPEC.get("outfile"):
        with open(SPEC["outfile"], "a") as fh:
            fh.write(out + "\n")


