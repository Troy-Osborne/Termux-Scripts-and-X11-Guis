    def apply_edit(self):
        i = self.edit_idx
        if i is None or i >= len(self.fields):
            return
        key = self.e["key"].get().strip()
        if not key:
            self.status.set("Key can't be empty")
            return
        if any(j != i and f["key"] == key for j, f in enumerate(self.fields)):
            self.status.set("Key '%s' already used" % key)
            return
        for n, v in self.e.items():
            self.fields[i][n] = v.get().strip() if n == "key" else v.get()
        self.status.set("")
        self.refresh(i)
        self.nb.select(self.tab_fields)

