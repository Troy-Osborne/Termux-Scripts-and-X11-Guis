def to_num(s, d=0):
    s = str(s).strip()
    try:
        return int(s)
    except ValueError:
        try:
            return float(s)
        except ValueError:
            return d


def truthy(s):
    return str(s).strip().lower() in ("1", "true", "yes", "on", "y", "t")


def normalize_field(f):
    t = f["type"]
    d = f["default"]
    out = {"key": f["key"], "label": f["label"], "type": t}
    if t in ("entry", "text"):
        out["default"] = d
    elif t == "check":
        out["default"] = truthy(d)
    elif t == "int":
        out["default"] = int(to_num(d, 0))
    elif t == "float":
        out["default"] = float(to_num(d, 0.0))
    elif t == "combo":
        opts = [o.strip() for o in f["options"].split(",") if o.strip()]
        out["options"] = opts
        out["default"] = d if d else (opts[0] if opts else "")
    elif t in ("spin", "scale"):
        lo, hi, st = to_num(f["min"], 0), to_num(f["max"], 100), to_num(f["step"], 1)
        if st == 0:
            st = 1
        dv = to_num(d, lo)
        if all(isinstance(x, int) for x in (lo, hi, st, dv)):
            pass
        else:
            lo, hi, st, dv = float(lo), float(hi), float(st), float(dv)
        out.update({"min": lo, "max": hi, "step": st, "default": dv})
    return out


def field_from_spec(f):
    t = f["type"]
    d = f.get("default", "")
    return {
        "key": f["key"], "label": f.get("label", ""), "type": t,
        "default": str(d) if d is not None else "",
        "options": ",".join(f.get("options", [])),
        "min": str(f.get("min", 0)), "max": str(f.get("max", 100)),
        "step": str(f.get("step", 1)),
    }


