    def sel(self):
        s = self.lb.curselection()
        return s[0] if s else None

    def refresh(self, select=None):
        self.lb.delete(0, "end")
        for f in self.fields:
            self.lb.insert("end", "%s  [%s]  %s" % (f["key"], f["type"], f["label"]))
        if select is not None and 0 <= select < len(self.fields):
            self.lb.selection_set(select)
            self.lb.see(select)

    def unique_key(self, base):
        existing = {f["key"] for f in self.fields}
        n = 1
        while "%s%d" % (base, n) in existing:
            n += 1
        return "%s%d" % (base, n)

    def add_field(self):
        k = self.unique_key("field")
        self.fields.append({"key": k, "label": k.capitalize(), "type": "entry",
                            "default": "", "options": "", "min": "0",
                            "max": "100", "step": "1"})
        self.refresh(len(self.fields) - 1)
        self.edit(len(self.fields) - 1)

    def dup_field(self):
        i = self.sel()
        if i is None:
            return
        f = dict(self.fields[i])
        f["key"] = self.unique_key(f["key"].rstrip("0123456789") or "field")
        self.fields.insert(i + 1, f)
        self.refresh(i + 1)

    def del_field(self):
        i = self.sel()
        if i is None:
            return
        del self.fields[i]
        self.refresh(min(i, len(self.fields) - 1))

    def move(self, d):
        i = self.sel()
        if i is None or not 0 <= i + d < len(self.fields):
            return
        self.fields[i], self.fields[i + d] = self.fields[i + d], self.fields[i]
        self.refresh(i + d)

    def edit_selected(self):
        i = self.sel()
        if i is not None:
            self.edit(i)

